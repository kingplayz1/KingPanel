import React, { useState } from 'react';
import { NavSection, ServerInstance } from '../types';

interface NotFound404ViewProps {
  server: ServerInstance;
  requestedPath?: string;
  onNavigate: (section: NavSection) => void;
  onShowToast: (
    title: string,
    body?: string,
    type?: 'success' | 'info' | 'warning' | 'error',
    icon?: string
  ) => void;
}

export const NotFound404View: React.FC<NotFound404ViewProps> = ({
  server,
  requestedPath = '/region/r.-404.-404.mca',
  onNavigate,
  onShowToast,
}) => {
  const [repairingChunk, setRepairingChunk] = useState(false);

  const handleRunChunkRepair = () => {
    setRepairingChunk(true);
    setTimeout(() => {
      setRepairingChunk(false);
      onShowToast(
        'Region Sector Regenerated',
        `Rebuilt chunk index for ${server.name} and redirected to Overview.`,
        'success',
        'build_circle'
      );
      onNavigate('overview');
    }, 900);
  };

  return (
    <main className="flex-1 flex flex-col bg-surface-dim overflow-y-auto items-center justify-center p-6 relative">
      {/* Ambient Background Diagnostic Grid */}
      <div
        className="absolute inset-0 pointer-events-none opacity-25"
        style={{
          backgroundImage:
            'radial-gradient(circle at 50% 35%, rgba(255, 123, 123, 0.14), transparent 55%), linear-gradient(to right, rgba(255,255,255,0.03) 1px, transparent 1px), linear-gradient(to bottom, rgba(255,255,255,0.03) 1px, transparent 1px)',
          backgroundSize: '100% 100%, 32px 32px, 32px 32px',
        }}
      />

      <div className="relative z-10 w-full max-w-3xl rounded-2xl bg-surface border border-error/40 shadow-2xl overflow-hidden">
        {/* Top Error Diagnostic Banner */}
        <div className="px-6 py-4 bg-error/15 border-b border-error/30 flex items-center justify-between flex-wrap gap-3">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-lg bg-error/20 border border-error/40 flex items-center justify-center text-error">
              <span className="material-symbols-outlined text-[20px]">broken_image</span>
            </div>
            <div>
              <div className="text-xs font-mono uppercase tracking-widest text-error font-bold">
                HTTP 404 • ERR_CHUNK_NOT_GENERATED
              </div>
              <div className="text-sm font-bold text-white">
                Unloaded Anvil Region Sector or Missing Workstation Route
              </div>
            </div>
          </div>

          <span className="px-2.5 py-1 rounded-md bg-surface-lowest border border-error/35 text-xs font-mono text-error font-bold">
            Coords: X: -404, Y: -64 (Void), Z: 404
          </span>
        </div>

        {/* Center 404 Visual & Stacktrace */}
        <div className="p-6 sm:p-8 space-y-6">
          <div className="grid grid-cols-1 md:grid-cols-12 gap-6 items-center">
            {/* Big 404 Emblem */}
            <div className="md:col-span-5 p-6 rounded-2xl bg-surface-lowest border border-outline-variant/25 text-center space-y-2">
              <div className="text-6xl font-extrabold font-mono tracking-tighter text-transparent bg-clip-text bg-gradient-to-br from-primary via-amber-300 to-error">
                404
              </div>
              <div className="text-xs font-mono uppercase tracking-widest text-white font-bold">
                Void Sector Reached
              </div>
              <p className="text-[11px] font-mono text-outline">
                Region file <code className="text-primary">r.-404.-404.mca</code> does not exist in
                the current world directory.
              </p>
            </div>

            {/* Right Explanation & Diagnostic Stacktrace */}
            <div className="md:col-span-7 space-y-3">
              <h2 className="text-base font-bold text-white">
                The requested panel view or server resource could not be located.
              </h2>
              <p className="text-xs text-on-surface-variant leading-relaxed">
                Either the route URI (<code className="text-primary font-mono">{requestedPath}</code>)
                was mistyped, the world chunk has not been pre-generated by Chunky yet, or the
                configuration file was moved.
              </p>

              {/* Terminal Stacktrace Box */}
              <div className="p-3.5 rounded-xl bg-surface-lowest border border-outline-variant/30 font-mono text-[11px] space-y-1 text-on-surface-variant overflow-x-auto">
                <div className="text-error font-bold">
                  java.nio.file.NoSuchFileException: {server.path}
                  {requestedPath.replace(/\//g, '\\')}
                </div>
                <div className="text-outline pl-3">
                  at io.papermc.paper.chunk.system.io.RegionFileIOThread.load(RegionFileIOThread.java:404)
                </div>
                <div className="text-outline pl-3">
                  at net.kingsmp.panel.router.FastPipeDispatcher.resolveView(FastPipeDispatcher.ts:118)
                </div>
                <div className="text-secondary pt-1">
                  [FastPipe Recovery] Safe fallback routes ready — 0 bytes corrupted.
                </div>
              </div>
            </div>
          </div>

          {/* Recovery Action Bar */}
          <div className="pt-4 border-t border-outline-variant/20 flex flex-wrap items-center justify-between gap-3">
            <div className="flex flex-wrap items-center gap-2.5">
              <button
                type="button"
                onClick={() => onNavigate('overview')}
                className="px-4 py-2.5 rounded-xl bg-gradient-to-r from-primary to-primary-container text-on-primary-container text-xs font-bold shadow-lg shadow-primary/20 flex items-center gap-2 cursor-pointer"
              >
                <span className="material-symbols-outlined text-[17px]">space_dashboard</span>
                Return to Overview Dashboard
              </button>

              <button
                type="button"
                onClick={() => onNavigate('console')}
                className="px-3.5 py-2.5 rounded-xl bg-surface-container-high hover:bg-surface-bright text-xs font-semibold text-white border border-outline-variant/30 flex items-center gap-1.5 cursor-pointer"
              >
                <span className="material-symbols-outlined text-[16px] text-secondary">
                  terminal
                </span>
                Open Live Console
              </button>

              <button
                type="button"
                onClick={() => onNavigate('files')}
                className="px-3.5 py-2.5 rounded-xl bg-surface-container-high hover:bg-surface-bright text-xs font-semibold text-white border border-outline-variant/30 flex items-center gap-1.5 cursor-pointer"
              >
                <span className="material-symbols-outlined text-[16px] text-primary">
                  folder_open
                </span>
                Browse Files
              </button>
            </div>

            <button
              type="button"
              onClick={handleRunChunkRepair}
              disabled={repairingChunk}
              className="px-3.5 py-2.5 rounded-xl bg-secondary/15 hover:bg-secondary/25 text-secondary border border-secondary/35 text-xs font-mono font-bold flex items-center gap-1.5 cursor-pointer"
            >
              <span
                className={`material-symbols-outlined text-[16px] ${
                  repairingChunk ? 'animate-spin' : ''
                }`}
              >
                build_circle
              </span>
              {repairingChunk ? 'Rebuilding Sector...' : 'Teleport to Spawn (Repair)'}
            </button>
          </div>
        </div>
      </div>
    </main>
  );
};
